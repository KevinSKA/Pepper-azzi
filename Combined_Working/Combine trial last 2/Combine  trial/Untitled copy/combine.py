@app.route("/edit_json", methods=["POST"])
def edit_json():
    try:
        data = request.get_json(force=True)

        choice = data.get("choice", "sunglasses").strip().lower()
        image_b64 = data.get("image_b64", "")

        if choice not in PROMPTS:
            return jsonify({"ok": False, "error": "Invalid choice"}), 400

        if not image_b64:
            return jsonify({"ok": False, "error": "No image_b64 provided"}), 400

        prompt = PROMPTS[choice]
        image_bytes = base64.b64decode(image_b64)

        with open(INPUT_PATH, "wb") as f:
            f.write(image_bytes)

        img = Image.open(INPUT_PATH)

        # Retry logic for transient 503 errors
        max_retries = 3
        response = None
        for attempt in range(1, max_retries + 1):
            try:
                log_gemini("REQUEST [attempt {}/{}] model={} choice={}".format(attempt, max_retries, MODEL_NAME, choice))
                response = client.models.generate_content(
                    model=MODEL_NAME,
                    contents=[prompt, img]
                )
                log_gemini("RESPONSE OK [attempt {}] candidates={}".format(
                    attempt, len(response.candidates) if getattr(response, 'candidates', None) else 0))
                break
            except Exception as api_err:
                log_gemini("ERROR [attempt {}/{}] {}: {}".format(attempt, max_retries, type(api_err).__name__, str(api_err)))
                if attempt < max_retries:
                    time.sleep(2 * attempt)  # exponential backoff
                else:
                    log_gemini("FAILED all {} retries for choice={}".format(max_retries, choice))
                    return jsonify({"ok": False, "error": "Gemini API error after {} retries: {}".format(max_retries, str(api_err))}), 503

        filename = "result_" + str(uuid.uuid4()) + ".png"
        output_path = os.path.join(STATIC_DIR, filename)

        ok = save_returned_image(response, output_path)
        if not ok:
            log_gemini("NO IMAGE in response for choice={}".format(choice))
            return jsonify({"ok": False, "error": "Gemini returned no image output"}), 500

        # UPDATE STARTS HERE
        global LATEST_RESULT_URL, LATEST_QR_URL
        
        result_url = "http://%s:%s/static/%s" % (LAPTOP_IP, FLASK_PORT, filename)
        LATEST_RESULT_URL = result_url

        # 1. Generate the QR Code linked to the result_url
        qr_image = qrcode.make(result_url)
        
        # 2. Save the QR Code to the static folder
        qr_filename = "qr_" + filename
        qr_output_path = os.path.join(STATIC_DIR, qr_filename)
        qr_image.save(qr_output_path)
        
        # 3. Create the URL for the QR code
        LATEST_QR_URL = "http://%s:%s/static/%s" % (LAPTOP_IP, FLASK_PORT, qr_filename)

        log_gemini("SUCCESS choice={} result_url={}".format(choice, result_url))

        return jsonify({
            "ok": True,
            "choice": choice,
            "result_url": result_url,
            "qr_url": LATEST_QR_URL # Pass this back just in case your frontend script needs it
        })
    except Exception as e:
        log_gemini("UNHANDLED ERROR: {}: {}".format(type(e).__name__, str(e)))
        return jsonify({"ok": False, "error": str(e)}), 500
    
