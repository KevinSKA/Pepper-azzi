def detect_local_ip():
    """
    Returns the LAN IP this machine uses to reach the outside world.
    Tries a UDP "connect" trick (no packets actually sent), then falls
    back to hostname resolution, then to 127.0.0.1.
    """
    ip = None
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            s.connect(("8.8.8.8", 80))
            ip = s.getsockname()[0]
        finally:
            s.close()
    except Exception:
        ip = None

    if not ip or ip.startswith("127."):
        try:
            ip = socket.gethostbyname(socket.gethostname())
        except Exception:
            ip = None

    if not ip or ip.startswith("127."):
        ip = "127.0.0.1"

    return ip


