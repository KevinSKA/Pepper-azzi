class MyHandler(BaseHTTPRequestHandler):

    def send_json_response(self, data, status_code=200):
        response = json.dumps(data).encode("utf-8")

        self.send_response(status_code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(response)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()
        self.wfile.write(response)

    def do_OPTIONS(self):
        self.send_response(200)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def do_GET(self):
        try:
            parsed_url = urlparse(self.path)
            path = parsed_url.path
            params = parse_qs(parsed_url.query)

            if path == "/students":
                students_list = get_present_students()
                self.send_json_response({
                    "success": True,
                    "students": students_list
                })

            elif path == "/send_attendance_email":
                password = params.get("password", [""])[0]

                if password != ADMIN_PASSWORD:
                    self.send_json_response({
                        "success": False,
                        "error": "Incorrect password"
                    }, 401)
                    return

                students_list = get_present_students()

                if not students_list:
                    self.send_json_response({
                        "success": False,
                        "error": "No students found in database"
                    }, 400)
                    return

                file_path, file_name = create_attendance_excel(students_list)
                send_email_with_attachment(file_path, file_name, len(students_list))

                self.send_json_response({
                    "success": True,
                    "message": "Attendance email sent successfully to {}".format(
                        EMAIL_RECEIVER
                    )
                })

            else:
                self.send_json_response({
                    "success": False,
                    "error": "Route not found"
                }, 404)

        except Exception as e:
            traceback.print_exc()
            self.send_json_response({
                "success": False,
                "error": str(e)
            }, 500)

    def log_message(self, format, *args):
        print("%s - - [%s] %s" % (
            self.client_address[0],
            self.log_date_time_string(),
            format % args
        ))


def run_attendance_server():
    server = HTTPServer((HOST, ATTENDANCE_PORT), MyHandler)
    print("Attendance server running on http://{}:{}".format(HOST, ATTENDANCE_PORT))
    server.serve_forever()


