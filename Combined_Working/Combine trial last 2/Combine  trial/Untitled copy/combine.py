def get_present_students():
    print("[DB] get_present_students() called")
    conn = get_db_connection()
    cursor = conn.cursor()

    # First check what tables exist
    try:
        cursor.execute("SHOW TABLES")
        tables = cursor.fetchall()
        print("[DB] Tables in '{}': {}".format(DB_CONFIG['database'], [t[0] for t in tables]))
    except Exception as e:
        print("[DB] SHOW TABLES failed: {}".format(str(e)))

    # Check table structure
    try:
        cursor.execute("DESCRIBE attendance")
        columns = cursor.fetchall()
        print("[DB] 'attendance' columns: {}".format([(c[0], c[1]) for c in columns]))
    except Exception as e:
        print("[DB] DESCRIBE attendance failed: {}".format(str(e)))

    # Count all rows
    try:
        cursor.execute("SELECT COUNT(*) FROM attendance")
        total = cursor.fetchone()[0]
        print("[DB] Total rows in attendance: {}".format(total))
    except Exception as e:
        print("[DB] COUNT(*) failed: {}".format(str(e)))

    # Show sample rows
    try:
        cursor.execute("SELECT * FROM attendance LIMIT 5")
        sample = cursor.fetchall()
        print("[DB] Sample rows (up to 5): {}".format(sample))
    except Exception as e:
        print("[DB] Sample query failed: {}".format(str(e)))

    cursor.execute("""
        SELECT DISTINCT student_name
        FROM attendance
        WHERE student_name IS NOT NULL
          AND TRIM(student_name) <> ''
        ORDER BY student_name ASC
    """)

    results = cursor.fetchall()
    students = [row[0] for row in results]
    print("[DB] Found {} distinct students: {}".format(len(students), students))

    cursor.close()
    conn.close()

    return students


def create_attendance_excel(students):
    wb = Workbook()
    ws = wb.active
    ws.title = "Attendance"

    ws["A1"] = "Present Students"
    ws["B1"] = "Generated At"

    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    for index, student in enumerate(students, start=2):
        ws["A{}".format(index)] = student
        ws["B{}".format(index)] = now_str

    ws.column_dimensions["A"].width = 30
    ws.column_dimensions["B"].width = 24

    file_name = "attendance_{}.xlsx".format(
        datetime.now().strftime("%Y%m%d_%H%M%S")
    )
    file_path = os.path.join(os.getcwd(), file_name)
    wb.save(file_path)

    return file_path, file_name


